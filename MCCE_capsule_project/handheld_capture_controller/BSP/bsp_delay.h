#ifndef __BSP_DELAY_H
#define __BSP_DELAY_H

#include "stm8s.h"


/*
 * ============================================================================
 * 初始化 TIM4
 *
 * TIM4 用于产生 1ms 系统节拍。
 * ============================================================================
 */
void Delay_Init(void);


/*
 * ============================================================================
 * 获取系统运行时间
 *
 * 返回：
 *
 *     系统启动以来经过的毫秒数
 *
 * 例如：
 *
 *     1000
 *
 * 表示大约运行了 1 秒。
 * ============================================================================
 */
uint32_t Delay_GetTick(void);


/*
 * ============================================================================
 * 毫秒延时
 *
 * 例如：
 *
 *     Delay_ms(10);
 *
 * 表示等待约 10ms。
 * ============================================================================
 */
void Delay_ms(uint32_t ms);


/*
 * ============================================================================
 * TIM4 中断调用
 *
 * 这个函数只能由 TIM4 ISR 调用。
 * 不要在普通代码里面调用。
 * ============================================================================
 */
void Delay_TickISR(void);

#endif