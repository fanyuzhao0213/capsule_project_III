/*
********************************************************************************
* Function Name : dataBuf_Init
* Description   : JPEG 数据缓存初始化
* Paramter      : None
* Return        : None
*
* 初始化内容：
*   ① 把 imgBuf_template 前 814 字节复制到 Data_Buf0
*        - bytes 0~127:   预头部（运行时会被 SD_Card_storage_imgdata 覆盖为 DeviceInfo）
*        - bytes 128~813: JPEG header（FF D8 + APP0 + DQT + DHT + SOF + SOS）
*
*   ② 把 Rec_Buf 和 Send_Buf 都指向 Data_Buf0
*        - Rec_Buf:  USART3 接收时填充 JPEG 数据到 [814..]
*        - Send_Buf: UART3 转发时从此读取 [128..] 到 UART3 payload
*
* 调用时机：do_main::app_program_Init() 中
********************************************************************************
*/
void jpeg_data_buf_Init(void)
{
	u16 i;

  // 复制 814 字节模板（前 128 字节预头部 + 后 686 字节 JPEG header）
  for(i = 0; i < (FRAME_HEADER_SIZE + IMAGE_HEADER_LEN); i++)
  {
		Data_Buf0[i] = imgBuf_template[i];
  }

  // Rec_Buf 和 Send_Buf 都指向同一个 Data_Buf0
  Rec_Buf  = Data_Buf0;
  Send_Buf = Data_Buf0;
}
